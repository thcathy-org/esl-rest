package com.esl.config;

import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;

import static org.junit.jupiter.api.Assertions.*;

class PhoneticQuestionWordUniqueIndexTest {

    @Test
    void addsUniqueIndexAndRejectsASecondWord() throws Exception {
        var dataSource = dataSource("unique-ok");
        jdbc(dataSource).update("INSERT INTO phonetic_question (WORD) VALUES ('alpha'), ('beta')");

        new PhoneticQuestionWordUniqueIndex(dataSource).ensure();
        new PhoneticQuestionWordUniqueIndex(dataSource).ensure();

        var second = jdbc(dataSource);
        assertThrows(Exception.class, () -> second.update("INSERT INTO phonetic_question (WORD) VALUES ('alpha')"));
        assertEquals(1, count(dataSource, "alpha"));
    }

    @Test
    void refusesToAddIndexWhenDuplicateWordsExist() {
        var dataSource = dataSource("unique-dup");
        jdbc(dataSource).update("INSERT INTO phonetic_question (WORD) VALUES ('same'), ('same')");

        var failure = assertThrows(IllegalStateException.class,
                () -> new PhoneticQuestionWordUniqueIndex(dataSource).ensure());
        assertTrue(failure.getMessage().contains("same"));
        assertEquals(2, count(dataSource, "same"));
        jdbc(dataSource).update("INSERT INTO phonetic_question (WORD) VALUES ('same')");
        assertEquals(3, count(dataSource, "same"));
    }

    private static JdbcDataSource dataSource(String name) {
        var dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:" + name + ";MODE=MySQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1");
        new JdbcTemplate(dataSource).execute("""
                CREATE TABLE phonetic_question (
                    PHONETICQUESTION_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    WORD VARCHAR(40)
                )
                """);
        return dataSource;
    }

    private static JdbcTemplate jdbc(JdbcDataSource dataSource) {
        return new JdbcTemplate(dataSource);
    }

    private static int count(JdbcDataSource dataSource, String word) {
        return jdbc(dataSource).queryForObject(
                "SELECT COUNT(*) FROM phonetic_question WHERE WORD = ?", Integer.class, word);
    }
}
